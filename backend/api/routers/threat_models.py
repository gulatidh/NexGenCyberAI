@router.post("/", response_model=ThreatModelSummary, status_code=201)
async def create_threat_model(
    client_id: str,
    payload: ThreatModelCreate,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """Persist a pending threat model and kick off generation in the
    background. Poll `GET /clients/{cid}/threat-models/{id}` for status."""
    if not db.query(Client.id).filter(Client.id == client_id).first():
        raise HTTPException(status_code=404, detail="Client not found")

    proj_id = payload.project_id
    if proj_id and not db.query(Project.id).filter(Project.id == proj_id, Project.client_id == client_id).first():
        raise HTTPException(status_code=404, detail="Project not found for this client")

    methodology = (payload.methodology or DEFAULT_METHODOLOGY).lower()
    if methodology not in METHODOLOGIES:
        raise HTTPException(
            status_code=400,
            detail=f"Unknown methodology '{methodology}'. Pick one of: {', '.join(METHODOLOGIES)}",
        )
    tm = ThreatModel(
        client_id=client_id,
        project_id=proj_id,
        name=(payload.name or "").strip() or None,
        scope_type=payload.scope_type or "client",
        scope_id=payload.scope_id,
        framework=payload.framework,
        methodology=methodology,
        status="pending",
        initiated_by=user.get("upn", user.get("preferred_username", "system")),
    )
    db.add(tm)
    db.commit()
    db.refresh(tm)
    background_tasks.add_task(generate_threat_model_bg, tm.id)
    return _summary_from(tm)


@router.get("/", response_model=List[ThreatModelSummary])
async def list_threat_models(
    client_id: str,
    db: Session = Depends(get_db),
    _=Depends(get_current_user),
):
    rows = (
        db.query(ThreatModel)
        .filter(ThreatModel.client_id == client_id)
        .order_by(ThreatModel.created_at.desc())
        .limit(200)
        .all()
    )
    # Collapse rescans: only the newest per (parent_threat_model_id ?? id).
    seen: set = set()
    out: List[Dict[str, Any]] = []
    rows_sorted = sorted(rows, key=lambda r: r.created_at or datetime.min, reverse=True)
    for r in rows_sorted:
        root = r.parent_threat_model_id or r.id
        if root in seen:
            continue
        seen.add(root)
        out.append(_summary_from(r))
    return out


@router.get("/{model_id}", response_model=ThreatModelDetail)
async def get_threat_model(
    client_id: str,
    model_id: str,
    db: Session = Depends(get_db),
    _=Depends(get_current_user),
):
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")
    return _detail_from(tm, db=db)


@router.get("/{model_id}/versions", response_model=List[ThreatModelSummary])
async def list_versions(
    client_id: str,
    model_id: str,
    db: Session = Depends(get_db),
    _=Depends(get_current_user),
):
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")
    root = tm.parent_threat_model_id or tm.id
    siblings = (
        db.query(ThreatModel)
        .filter(ThreatModel.client_id == client_id)
        .filter((ThreatModel.id == root) | (ThreatModel.parent_threat_model_id == root))
        .order_by(ThreatModel.created_at.desc())
        .all()
    )
    return [_summary_from(s) for s in siblings]


@router.post("/{model_id}/rescan", response_model=ThreatModelSummary, status_code=201)
async def rescan(
    client_id: str,
    model_id: str,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """Generate a new version of an existing threat model. Same scope +
    framework as the original; new row links via parent_threat_model_id."""
    original = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not original:
        raise HTTPException(status_code=404, detail="Threat model not found")
    root = original.parent_threat_model_id or original.id
    new = ThreatModel(
        client_id=client_id,
        project_id=original.project_id,
        name=original.name,
        scope_type=original.scope_type,
        scope_id=original.scope_id,
        framework=original.framework,
        methodology=original.methodology or DEFAULT_METHODOLOGY,
        status="pending",
        initiated_by=user.get("upn", user.get("preferred_username", "system")),
        parent_threat_model_id=root,
    )
    db.add(new)
    db.commit()
    db.refresh(new)
    background_tasks.add_task(generate_threat_model_bg, new.id)
    return _summary_from(new)


@router.post("/{model_id}/threats/{threat_id}/convert-to-risk", status_code=201)
async def convert_threat_to_risk(
    client_id: str,
    model_id: str,
    threat_id: str,
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """Create a Risk Register entry from a single threat in this model.

    Idempotent: if a Risk already exists for (model_id, threat_id), return
    the existing one with 200 instead of 201."""
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")

    existing = (
        db.query(Risk)
        .filter(Risk.source_threat_model_id == tm.id, Risk.source_threat_id == threat_id)
        .first()
    )
    if existing:
        return {"risk_id": existing.id, "created": False}

    threats = tm.threats_json or []
    threat = next((t for t in threats if str(t.get("id")) == threat_id), None)
    if not threat:
        raise HTTPException(status_code=404, detail=f"Threat {threat_id} not in model")

    mitigations = [m for m in (tm.mitigations_json or []) if str(m.get("threat_id")) == threat_id]
    risk = _threat_to_risk(tm=tm, threat=threat, mitigations=mitigations, user=user)
    db.add(risk)
    db.commit()
    db.refresh(risk)
    return {"risk_id": risk.id, "created": True}


@router.post("/{model_id}/convert-all-to-risks", response_model=ConvertResult)
async def convert_all_threats_to_risks(
    client_id: str,
    model_id: str,
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """Bulk-convert every threat in the model to Risk Register entries,
    skipping any that already have a Risk for this (model_id, threat_id)."""
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")

    already = {
        sid for (sid,) in db.query(Risk.source_threat_id)
        .filter(Risk.source_threat_model_id == tm.id, Risk.source_threat_id.isnot(None))
        .all()
    }
    mitigations_by_threat: Dict[str, List[Dict[str, Any]]] = {}
    for m in tm.mitigations_json or []:
        mitigations_by_threat.setdefault(str(m.get("threat_id")), []).append(m)

    created_ids: List[str] = []
    skipped = 0
    for threat in tm.threats_json or []:
        tid = str(threat.get("id") or "")
        if not tid:
            skipped += 1
            continue
        if tid in already:
            skipped += 1
            continue
        risk = _threat_to_risk(
            tm=tm, threat=threat, mitigations=mitigations_by_threat.get(tid, []), user=user,
        )
        db.add(risk)
        db.flush()
        created_ids.append(risk.id)
    db.commit()
    return ConvertResult(created=len(created_ids), skipped=skipped, risk_ids=created_ids)


@router.get("/{model_id}/drawio")
async def get_threat_model_drawio(
    client_id: str,
    model_id: str,
    download: int = 0,
    db: Session = Depends(get_db),
    _=Depends(get_current_user),
):
    """Render this threat model's DFD as draw.io / mxGraph XML.

    - `?download=1` returns the XML as a `.drawio` attachment, ready to
      open in draw.io desktop or diagrams.net.
    - default returns JSON `{xml, filename}` so the embedded viewer in
      the frontend can postMessage the XML into the diagrams.net iframe.
    """
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")

    title = tm.name or f"Threat Model {tm.id[:8]}"
    xml = render_drawio_xml(
        title=title,
        components=tm.components_json or [],
        data_flows=tm.data_flows_json or [],
        executive_summary=tm.executive_summary,
    )
    safe_name = "".join(c if c.isalnum() or c in "-_" else "-" for c in title)[:80] or "threat-model"
    filename = f"{safe_name}.drawio"
    if download:
        return Response(
            content=xml,
            media_type="application/vnd.jgraph.mxfile",
            headers={"Content-Disposition": f'attachment; filename="{filename}"'},
        )
    return {"xml": xml, "filename": filename}


class FromDiagramResponse(BaseModel):
    model_id: str
    components: List[Dict[str, Any]]
    data_flows: List[Dict[str, Any]]
    source: str
    warnings: List[str] = []


@router.post("/from-diagram", response_model=FromDiagramResponse, status_code=201)
async def create_from_diagram(
    client_id: str,
    file: UploadFile = File(...),
    project_id: Optional[str] = Form(None),
    name: Optional[str] = Form(None),
    framework: Optional[str] = Form(None),
    methodology: Optional[str] = Form(None),
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """Upload an architecture diagram (.drawio / .xml / .pdf / .jpg / .png),
    extract components + data flows, and persist a ThreatModel row in
    `extracted_review` status.

    The user reviews / edits the extracted DFD on the detail page, then
    calls `POST /{id}/start-modeling` to kick off AI threat generation."""
    if not db.query(Client.id).filter(Client.id == client_id).first():
        raise HTTPException(status_code=404, detail="Client not found")
    if project_id and not db.query(Project.id).filter(
        Project.id == project_id, Project.client_id == client_id,
    ).first():
        raise HTTPException(status_code=404, detail="Project not found for this client")

    data = await file.read()
    if len(data) > _MAX_UPLOAD_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f"File too large ({len(data)} bytes). Max {_MAX_UPLOAD_BYTES} bytes.",
        )
    if not data:
        raise HTTPException(status_code=400, detail="Empty file.")
    if not any((file.filename or "").lower().endswith(ext) for ext in SUPPORTED_EXTENSIONS):
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file extension. Allowed: {sorted(SUPPORTED_EXTENSIONS)}",
        )

    try:
        extracted = await extract_diagram(file.filename or "", file.content_type, data)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc))
    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc))

    chosen_methodology = (methodology or DEFAULT_METHODOLOGY).lower()
    if chosen_methodology not in METHODOLOGIES:
        chosen_methodology = DEFAULT_METHODOLOGY
    chosen_framework: Optional[FrameworkType] = None
    if framework:
        try:
            chosen_framework = FrameworkType(framework)
        except ValueError:
            chosen_framework = None

    fallback_name = (file.filename or "Diagram upload").rsplit(".", 1)[0]
    tm = ThreatModel(
        client_id=client_id,
        project_id=project_id,
        name=(name or "").strip() or fallback_name[:200],
        scope_type="diagram",
        scope_id=None,
        framework=chosen_framework,
        methodology=chosen_methodology,
        status="extracted_review",
        initiated_by=user.get("upn", user.get("preferred_username", "system")),
        components_json=extracted["components"],
        data_flows_json=extracted["data_flows"],
        threats_json=[],
        mitigations_json=[],
        dfd_mermaid=None,
        executive_summary=(
            f"Diagram-derived architecture from uploaded {extracted['source']} "
            f"file `{file.filename}`. Pending AI threat analysis."
        ),
    )
    db.add(tm)
    db.commit()
    db.refresh(tm)
    return FromDiagramResponse(
        model_id=tm.id,
        components=extracted["components"],
        data_flows=extracted["data_flows"],
        source=extracted["source"],
        warnings=extracted.get("warnings", []),
    )


class ReviewedDfd(BaseModel):
    components: Optional[List[Dict[str, Any]]] = None
    data_flows: Optional[List[Dict[str, Any]]] = None
    name: Optional[str] = None
    framework: Optional[FrameworkType] = None
    methodology: Optional[str] = None


@router.post("/{model_id}/start-modeling", response_model=ThreatModelSummary, status_code=202)
async def start_modeling_from_diagram(
    client_id: str,
    model_id: str,
    payload: ReviewedDfd,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
):
    """After the user has reviewed (and optionally edited) the
    diagram-extracted components and data flows, accept the reviewed
    payload and kick off AI threat generation on top of it."""
    tm = db.query(ThreatModel).filter(
        ThreatModel.id == model_id, ThreatModel.client_id == client_id,
    ).first()
    if not tm:
        raise HTTPException(status_code=404, detail="Threat model not found")
    if tm.status != "extracted_review":
        raise HTTPException(
            status_code=409,
            detail=f"Cannot start modelling — status is '{tm.status}', expected 'extracted_review'.",
        )

    if payload.components is not None:
        tm.components_json = payload.components
    if payload.data_flows is not None:
        tm.data_flows_json = payload.data_flows
    if payload.name:
        tm.name = payload.name.strip()[:200] or tm.name
    if payload.framework is not None:
        tm.framework = payload.framework
    if payload.methodology:
        m = payload.methodology.lower()
        if m in METHODOLOGIES:
            tm.methodology = m
    tm.status = "pending"
    tm.initiated_by = user.get("upn", user.get("preferred_username", "system"))
    db.commit()
    db.refresh(tm)
