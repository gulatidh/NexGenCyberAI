"""Threat Model CRUD + AI generation endpoints.

Threat models are generated by `services/threat_modeler.py` — this router
just persists the request, kicks off the background job, and serves
read/list/delete operations.

Versioning mirrors the scans pattern: rescanning a threat model creates a
new row with `parent_threat_model_id` pointing at the root of the chain.
"""
from __future__ import annotations
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, BackgroundTasks, Depends, File, Form, HTTPException, UploadFile
from fastapi.responses import Response
from pydantic import BaseModel
from sqlalchemy.orm import Session

from api.models.models import Client, FrameworkType, Project, Risk, RiskLevel, ThreatModel
from db.database import get_db
from core.security import get_current_user
from services.diagram_extractor import SUPPORTED_EXTENSIONS, extract as extract_diagram
from services.drawio_renderer import render_drawio_xml
from services.threat_modeler import (
    DEFAULT_METHODOLOGY, METHODOLOGIES, generate_threat_model_bg, methodology_catalog,
)

# Max upload size for diagram files. PDFs can be big with embedded fonts;
# images we expect to be small. 10 MB is plenty for any reasonable
# architecture diagram and protects the API from accidental abuse.
_MAX_UPLOAD_BYTES = 10 * 1024 * 1024


# Severity → (likelihood, impact, RiskLevel) for the threat→risk mapping.
# Keep the dimensions modest: a single high-severity threat shouldn't
# necessarily mean catastrophe — likelihood / impact get tuned in the
# Risk Register afterwards.
_SEV_TO_RISK: Dict[str, tuple[int, int, RiskLevel]] = {
    "critical": (5, 5, RiskLevel.CRITICAL),
    "high": (4, 4, RiskLevel.HIGH),
    "medium": (3, 3, RiskLevel.MEDIUM),
    "low": (2, 2, RiskLevel.LOW),
    "info": (1, 2, RiskLevel.LOW),
}

router = APIRouter(prefix="/clients/{client_id}/threat-models", tags=["threat-models"])

# Public methodology catalog — no client scoping, used by the create dialog.
methodology_router = APIRouter(prefix="/threat-models", tags=["threat-models"])


@methodology_router.get("/methodologies")
async def list_methodologies(_=Depends(get_current_user)):
    """Return the catalog of supported threat-modelling methodologies for
    the New Threat Model dialog's picker."""
    return {"methodologies": methodology_catalog(), "default": DEFAULT_METHODOLOGY}


@methodology_router.get("/library/{source}/{source_id}")
async def get_library_entry(
    source: str,
    source_id: str,
    db: Session = Depends(get_db),
    _=Depends(get_current_user),
):
    """Look up a single threat-library entry. Powers the tooltip on a
    CAPEC / ATT&CK chip on the Threat Model detail page so the user can
    see what a reference actually means."""
    from api.models.models import ThreatLibrary
    src = (source or "").lower()
    if src not in ("capec", "attack"):
        raise HTTPException(status_code=400, detail="source must be 'capec' or 'attack'")
    row = (
        db.query(ThreatLibrary)
        .filter(ThreatLibrary.source == src, ThreatLibrary.source_id == source_id)
        .first()
    )
    if not row:
        raise HTTPException(
            status_code=404,
            detail=f"{source_id} not in cache — run a Sync to refresh the threat library.",
        )
    return {
        "source": row.source,
        "source_id": row.source_id,
        "name": row.name,
        "description": row.description,
        "category": row.category,
        "severity_default": row.severity_default,
        "mitigation_hint": row.mitigation_hint,
        "related_cwes": row.related_cwes or [],
        "extra": row.extra or {},
    }


